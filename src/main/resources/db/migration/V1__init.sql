-- Midas Core 初始 schema（PostgreSQL）
-- 金额统一使用 NUMERIC(19,4)，与实体上的 precision/scale 保持一致

CREATE TABLE user_record (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255)   NOT NULL,
    balance NUMERIC(19, 4) NOT NULL
);

CREATE TABLE transaction_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id        VARCHAR(64)    NOT NULL,
    sender_id    BIGINT         NOT NULL,
    recipient_id BIGINT         NOT NULL,
    amount       NUMERIC(19, 4) NOT NULL,
    incentive    NUMERIC(19, 4) NOT NULL,
    status       VARCHAR(16)    NOT NULL,
    fail_reason  VARCHAR(255),
    created_at   TIMESTAMP      NOT NULL,
    CONSTRAINT uk_transaction_tx_id UNIQUE (tx_id)
);

CREATE INDEX idx_transaction_sender ON transaction_record (sender_id);
CREATE INDEX idx_transaction_recipient ON transaction_record (recipient_id);
CREATE INDEX idx_transaction_created_at ON transaction_record (created_at);
